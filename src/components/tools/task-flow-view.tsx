const symbolScale = (screen: [number, number]) => (DECISION_W * screen[0]) / GUIDE.decision[0]
const sizeOf = (kind: FlowGraphNodeKind, screen: [number, number]): [number, number] => {
  const s = symbolScale(screen)
  if (kind === 'screen') return screen
  if (kind === 'decision') return [GUIDE.decision[0] * s, GUIDE.decision[1] * s]
  if (kind === 'note') return [GUIDE.note[0] * s, GUIDE.note[1] * s]
  return [GUIDE.process[0] * s, GUIDE.process[1] * s]
}
