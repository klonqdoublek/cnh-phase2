/* ── subgraph ─────────────────────────────────────────────────────────────── */

function pickSubgraph(graph: FlowGraph, section: string) {
  if (section === WHOLE) return { nodes: graph.nodes, edges: graph.edges, exits: new Map<string, FlowGraphNode[]>() }
  const byId = new Map(graph.nodes.map((n) => [n.id, n]))
  const nb = new Map<string, Set<string>>()
  for (const e of graph.edges) {
    if (!nb.has(e.from)) nb.set(e.from, new Set())
    if (!nb.has(e.to)) nb.set(e.to, new Set())
    nb.get(e.from)!.add(e.to)
    nb.get(e.to)!.add(e.from)
  }
  const keep = new Set(graph.nodes.filter((n) => sectionOf(n) === section).map((n) => n.id))
  const own = graph.nodes.filter((n) => keep.has(n.id) && n.x != null && n.y != null) as Box[]
  const area = bboxOf(own)
  for (const n of own.length ? graph.nodes : []) {
    if (n.x == null || n.y == null || keep.has(n.id)) continue
    const cx = n.x + (n.w ?? 0) / 2
    const cy = n.y + (n.h ?? 0) / 2
    if (cx >= area.x && cx <= area.x + area.w && cy >= area.y && cy <= area.y + area.h) keep.add(n.id)
  }
  for (let grew = true; grew; ) {
    grew = false
    for (const n of graph.nodes) {
      if (keep.has(n.id) || n.kind === 'screen' || n.kind === 'note') continue
      const around = [...(nb.get(n.id) ?? [])]
      const inside = around.filter((id) => keep.has(id)).length
      const boxless = n.x == null
      if (inside >= 2 || (around.length === 1 && inside === 1) || (boxless && inside >= 1)) {
        keep.add(n.id)
        grew = true
      }
    }
  }
  const edges = graph.edges.filter((e) => keep.has(e.from) && keep.has(e.to))
  const exits = new Map<string, FlowGraphNode[]>()
  for (const e of graph.edges) {
    if (!keep.has(e.from) || keep.has(e.to)) continue
    const to = byId.get(e.to)
    if (!to) continue
    const list = exits.get(e.from) ?? []
    if (!list.some((t) => t.id === to.id)) list.push(to)
    exits.set(e.from, list)
  }
  return { nodes: graph.nodes.filter((n) => keep.has(n.id)), edges, exits }
}

/* ── layout ───────────────────────────────────────────────────────────────── */

function place(nodes: FlowGraphNode[], edges: FlowGraphEdge[], screen: [number, number]): Placed[] {
  const sized = nodes.map((n) => {
    const [w, h] = sizeOf(n.kind, screen)
    return { ...n, w: n.w ?? w, h: n.h ?? h }
  })
  const boxed = sized.filter((n) => n.x != null && n.y != null)
  if (boxed.length) {
    const at = new Map(boxed.map((n) => [n.id, { ...n, x: n.x!, y: n.y! }]))
    const bottom = Math.max(...boxed.map((n) => n.y! + n.h))
    let spare = Math.min(...boxed.map((n) => n.x!))
    return sized.map((n) => {
      const placed = at.get(n.id)
      if (placed) return placed
      const inEdge = edges.find((e) => e.to === n.id && at.has(e.from))
      const outEdge = edges.find((e) => e.from === n.id && at.has(e.to))
      const anchor = at.get(inEdge?.from ?? outEdge?.to ?? '')
      if (!anchor) {
        const x = spare
        spare += n.w + LOOSE_GAP
        return { ...n, x, y: bottom + LOOSE_GAP }
      }
      const y = anchor.y + Math.min(anchor.h, screen[1]) / 2 - n.h / 2
      return { ...n, x: inEdge ? anchor.x + anchor.w + LOOSE_GAP : anchor.x - n.w - LOOSE_GAP, y }
    })
  }
  /* No board coordinates (always, for a code graph): layered layout — columns by the
     LONGEST path from the roots over forward edges, so a step drawn after another always
     sits to its right; each column is centred on the tallest one. A back edge (one that
     returns to an earlier column) does not move anything. */
  const ids = new Set(nodes.map((n) => n.id))
  const into = new Map<string, number>()
  /* A way-back edge does not make its target a later step: "Cancel" back to the list must
     not cost the list its place as the entry. */
  for (const e of edges) if (e.style !== 'back' && ids.has(e.from) && ids.has(e.to)) into.set(e.to, (into.get(e.to) ?? 0) + 1)
  const rank = new Map<string, number>()
  const order = nodes.filter((n) => !into.get(n.id)).map((n) => n.id)
  if (!order.length && nodes[0]) order.push(nodes[0].id)
  order.forEach((id) => rank.set(id, 0))
  /* BFS first (every node gets a column), then relax forward edges a bounded number of times */
  for (let i = 0; i < order.length; i++)
    for (const e of edges)
      if (e.from === order[i] && ids.has(e.to) && !rank.has(e.to)) {
        rank.set(e.to, rank.get(order[i])! + 1)
        order.push(e.to)
      }
  const seen = new Map(order.map((id, i) => [id, i]))
  for (let pass = 0; pass < nodes.length; pass++) {
    let moved = false
    for (const e of edges) {
      if (e.style === 'back' || !rank.has(e.from) || !rank.has(e.to)) continue
      if ((seen.get(e.to) ?? 0) < (seen.get(e.from) ?? 0)) continue
      const want = rank.get(e.from)! + 1
      if (rank.get(e.to)! < want) {
        rank.set(e.to, want)
        moved = true
      }
    }
    if (!moved) break
  }
  /* Rows by flow: the MAIN flow (reached from the roots over solid, drawn edges only — the
     happy path) is one row across the top, every main node centred on the same line; a node
     reached only through an alternative or way-back edge stacks below it, in its column. */
  const main = mainOf(nodes, edges)
  const cols = new Map<number, (typeof sized)[number][]>()
  for (const n of sized) {
    const r = rank.get(n.id) ?? 0
    cols.set(r, [...(cols.get(r) ?? []), n])
  }
  const colW = new Map([...cols].map(([r, list]) => [r, Math.max(...list.map((n) => n.w))]))
  const colX = new Map<number, number>()
  let x = 0
  for (const r of [...cols.keys()].sort((a, b) => a - b)) {
    colX.set(r, x)
    x += colW.get(r)! + RANK_GAP
  }
  const lead = (list: (typeof sized)[number][]) => list.find((n) => main.has(n.id))
  const band = Math.max(...[...cols.values()].map((list) => lead(list)?.h ?? 0))
  const placed: Placed[] = []
  for (const [r, list] of cols) {
    const top = lead(list)
    let y = band + ROW_GAP
    for (const n of list) {
      const at = colX.get(r)! + (colW.get(r)! - n.w) / 2
      if (n === top) placed.push({ ...n, x: at, y: (band - n.h) / 2, col: r })
      else {
        placed.push({ ...n, x: at, y, col: r })
        y += n.h + LOOSE_GAP
      }
    }
  }
  /* FEWEST BENDS ("ให้เส้นไม่หักที่สุด", Korn 2026-10-05): a symbol on the main row sits level
     with the connector that brings it — the control it is tapped from, or the symbol before
     it — so that connector runs straight instead of stepping to the row's middle. */
  const box = new Map(placed.map((p) => [p.id, p]))
  for (const r of [...cols.keys()].sort((a, b) => a - b)) {
    const n = lead(cols.get(r)!)
    if (!n || n.kind === 'screen') continue
    const e = edges.find((x) => x.to === n.id && (x.style ?? 'solid') === 'solid' && !x.inferred && main.has(x.from) && box.has(x.from))
    if (!e) continue
    const s = box.get(e.from)!
    const cy = e.touch && s.kind === 'screen' ? s.y + ((e.touch.y + e.touch.h / 2) * s.h) / screen[1] : s.y + s.h / 2
    const p = box.get(n.id)!
    p.y = clamp(cy - p.h / 2, 0, Math.max(0, band - p.h))
  }
  return nodes.map((n) => placed.find((p) => p.id === n.id)!)
}

/* The MAIN flow — the guideline's "Main / Happy case": every node reached from the entry over
   solid, drawn edges. A way-back edge does not make its target a later step. Used for the rows
   and for the symbol colour (purple on the main flow, grey off it). */
function mainOf(nodes: FlowGraphNode[], edges: FlowGraphEdge[]): Set<string> {
  const ids = new Set(nodes.map((n) => n.id))
  const into = new Set(edges.filter((e) => e.style !== 'back' && ids.has(e.from) && ids.has(e.to)).map((e) => e.to))
  const main = new Set(nodes.filter((n) => !into.has(n.id)).map((n) => n.id))
  if (!main.size && nodes[0]) main.add(nodes[0].id)
  for (let i = 0, q = [...main]; i < q.length; i++)
    for (const e of edges)
      if (e.from === q[i] && ids.has(e.to) && (e.style ?? 'solid') === 'solid' && !e.inferred && !main.has(e.to)) {
        main.add(e.to)
        q.push(e.to)
      }
  return main
}

function bboxOf(nodes: Box[]): Box {
  if (!nodes.length) return { x: 0, y: 0, w: 1, h: 1 }
  const x0 = Math.min(...nodes.map((n) => n.x))
  const y0 = Math.min(...nodes.map((n) => n.y))
  const x1 = Math.max(...nodes.map((n) => n.x + n.w))
  const y1 = Math.max(...nodes.map((n) => n.y + n.h))
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 }
}

/* Orthogonal route between two boxes: side to side when they do not overlap horizontally,
   top/bottom otherwise. */
function elbow(a: Box, b: Box): number[][] {
  const acx = a.x + a.w / 2
  const acy = a.y + a.h / 2
  const bcx = b.x + b.w / 2
  const bcy = b.y + b.h / 2
  if (b.x >= a.x + a.w || b.x + b.w <= a.x) {
    const right = bcx > acx
    const sx = right ? a.x + a.w : a.x
    const ex = right ? b.x : b.x + b.w
    const mx = (sx + ex) / 2
    return [
      [sx, acy],
      [mx, acy],
      [mx, bcy],
      [ex, bcy],
    ]
  }
  const down = bcy > acy
  const sy = down ? a.y + a.h : a.y
  const ey = down ? b.y : b.y + b.h
  const my = (sy + ey) / 2
  return [
    [acx, sy],
    [acx, my],
    [bcx, my],
    [bcx, ey],
  ]
}

function halfway(pts: number[][], f = 0.5): number[] {
  const seg = pts.slice(1).map((p, i) => Math.hypot(p[0] - pts[i][0], p[1] - pts[i][1]))
  let left = seg.reduce((s, l) => s + l, 0) * f
  for (let i = 0; i < seg.length; i++) {
    if (left <= seg[i] || i === seg.length - 1) {
      const t = seg[i] ? left / seg[i] : 0
      return [pts[i][0] + (pts[i + 1][0] - pts[i][0]) * t, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * t]
    }
    left -= seg[i]
  }
  return pts[0]
}

