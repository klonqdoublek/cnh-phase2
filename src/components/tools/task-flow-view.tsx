export function TaskFlowView({ graph, renderScreen, currentRoute, onOpen, wireframe = false, className }: TaskFlowViewProps) {
  const sections = useMemo(() => sectionsOf(graph), [graph])
  const homeSection = useMemo(() => {
    if (sections.length < 2) return WHOLE
    const n = graph.nodes.find((x) => x.route && x.route === currentRoute)
    return n ? sectionOf(n) : WHOLE
  }, [graph, sections, currentRoute])
  const [section, setSection] = useState(homeSection)
  /* a new graph (another archive entry, same mounted view) starts on ITS home section — the
     previous graph's section name matched nothing and drew an empty board */
  useEffect(() => setSection(homeSection), [homeSection, graph])
  const [wf, setWf] = useState(wireframe)
  useEffect(() => setWf(wireframe), [wireframe])

  const screenSize = useMemo<[number, number]>(
    () => (graph.screen ? [graph.screen.w, graph.screen.h] : [1920, 1080]),
    [graph.screen],
  )
  const sub = useMemo(() => pickSubgraph(graph, section), [graph, section])
  const placed = useMemo(() => place(sub.nodes, sub.edges, screenSize), [sub, screenSize])
  const byId = useMemo(() => new Map(placed.map((n) => [n.id, n])), [placed])
  const bb = useMemo(() => bboxOf(placed), [placed])

  const port = useRef<HTMLDivElement>(null)
  const [size, setSize] = useState({ w: 0, h: 0 })
  useLayoutEffect(() => {
    const el = port.current
    if (!el) return
    const ro = new ResizeObserver(() => setSize({ w: el.clientWidth, h: el.clientHeight }))
    ro.observe(el)
    setSize({ w: el.clientWidth, h: el.clientHeight })
    return () => ro.disconnect()
  }, [])

  const [view, setView] = useState<View>({ k: 0.1, tx: 0, ty: 0 })
  const fit = useCallback(() => {
    if (!size.w || !size.h) return
    const k = clamp(Math.min((size.w - FIT_PAD * 2) / bb.w, (size.h - FIT_PAD * 2) / bb.h), ZOOM_MIN, 1)
    setView({ k, tx: (size.w - bb.w * k) / 2, ty: (size.h - bb.h * k) / 2 })
  }, [size.w, size.h, bb])
  useEffect(fit, [fit])

  /* Wheel, the Figma way (the people reading this are designers): scrolling — a mouse wheel
     or two fingers on a trackpad — PANS; a pinch (which the browser reports as a wheel event
     with ctrlKey) or ⌘/Ctrl + wheel ZOOMS about the cursor. Until 2026-10-05 every wheel
     event zoomed, so a trackpad scroll flung the view in and out ("zoom in zoom out ยากจัง",
     Korn). One event is capped at 35% so a mouse notch and a pinch feel alike.
     Non-passive so the page does not scroll with it. */
  useEffect(() => {
    const el = port.current
    if (!el) return
    const onWheel = (e: WheelEvent) => {
      e.preventDefault()
      const unit = e.deltaMode === 1 ? 16 : e.deltaMode === 2 ? el.clientHeight : 1
      const dx = e.deltaX * unit
      const dy = e.deltaY * unit
      if (!(e.ctrlKey || e.metaKey)) {
        setView((v) => ({ ...v, tx: v.tx - dx, ty: v.ty - dy }))
        return
      }
      const r = el.getBoundingClientRect()
      const cx = e.clientX - r.left
      const cy = e.clientY - r.top
      setView((v) => {
        const k = clamp(v.k * Math.exp(-clamp(dy, -30, 30) * 0.01), ZOOM_MIN, ZOOM_MAX)
        return { k, tx: cx - (cx - v.tx) * (k / v.k), ty: cy - (cy - v.ty) * (k / v.k) }
      })
    }
    el.addEventListener('wheel', onWheel, { passive: false })
    return () => el.removeEventListener('wheel', onWheel)
  }, [])

  /* drag = pan; a drag of more than a few px swallows the click that ends it */
  const drag = useRef<{ x: number; y: number; tx: number; ty: number; moved: boolean } | null>(null)
  const dragged = useRef(false)
  const onPointerDown = (e: PointerEvent) => {
    drag.current = { x: e.clientX, y: e.clientY, tx: view.tx, ty: view.ty, moved: false }
    dragged.current = false
  }
  const onPointerMove = (e: PointerEvent) => {
    const d = drag.current
    if (!d) return
    const dx = e.clientX - d.x
    const dy = e.clientY - d.y
    if (!d.moved && Math.hypot(dx, dy) < 4) return
    if (!d.moved) port.current?.setPointerCapture(e.pointerId)
    d.moved = true
    dragged.current = true
    setView((v) => ({ ...v, tx: d.tx + dx, ty: d.ty + dy }))
  }
  const onPointerUp = () => {
    drag.current = null
  }
  const zoomTo = (target: (k: number) => number) =>
    setView((v) => {
      const k = clamp(target(v.k), ZOOM_MIN, ZOOM_MAX)
      const cx = size.w / 2
      const cy = size.h / 2
      return { k, tx: cx - (cx - v.tx) * (k / v.k), ty: cy - (cy - v.ty) * (k / v.k) }
    })

  const open = (route?: string) => {
    if (route && !dragged.current) onOpen?.(route)
  }
  const goTo = (n: FlowGraphNode) => setSection(sectionOf(n))

  const { k } = view
  const vis = { x: -view.tx / k, y: -view.ty / k, w: size.w / k, h: size.h / k }
  const inView = (n: Placed) =>
    n.x - bb.x < vis.x + vis.w * 1.25 &&
    n.x - bb.x + n.w > vis.x - vis.w * 0.25 &&
    n.y - bb.y < vis.y + vis.h * 1.25 &&
    n.y - bb.y + n.h > vis.y - vis.h * 0.25
  const labelK = Math.max(1, LABEL_PX / k)
  const showLabels = k * labelK * 18 >= 8
  /* Arrows at the guideline's native size per 1920 of screen (4 wide, dash 8 / 8, labels 24/36 —
     what the CNH web board draws), never thinner than 1.5 px on screen. */
  const guide = screenSize[0] / WEB_SCREEN
  const stroke = Math.max(4 * guide, 1.5 / k)
  const rel = (n: Box) => ({ x: n.x - bb.x, y: n.y - bb.y, w: n.w, h: n.h })
  const fitted = (n: Placed) => {
    const base = TEXT_BASE[n.kind] ?? n.w
    const s = n.w / base
    return { width: base, height: n.h / s, transform: `scale(${s})` }
  }
  const col = (n: Box) => n.x
  /* The guideline's 6. Touch area (3085:9499): the control on the source screen that triggers
     the connector, measured in that screen's px (edge.touch). The connector leaves from it. */
  const touchBox = (e: FlowGraphEdge, a: Placed): Box | null => {
    if (!e.touch) return null
    const A = rel(a)
    const fx = A.w / screenSize[0]
    const fy = A.h / screenSize[1]
    return { x: A.x + e.touch.x * fx, y: A.y + e.touch.y * fy, w: e.touch.w * fx, h: e.touch.h * fy }
  }
  /* Guideline rule 4, "Minimal Arrow": a jump BACK to an earlier screen is not a long line round
     the board but a pair of Node Connectors (4.4) carrying the same letter — one under the
     source, one under the target, each a short stub. Placed above the node instead when
     something sits below it. */
  const R = (GUIDE.decision[0] * symbolScale(screenSize) * CONNECTOR_PER_DECISION) / 2
  const spot = (n: Placed, t?: Box | null) => {
    const b = rel(n)
    const cx = t ? t.x + t.w / 2 : b.x + b.w / 2
    const below = b.y + b.h + LOOSE_GAP / 2 + R
    const clash = placed.some((o) => o.id !== n.id && Math.abs(o.x - bb.x + o.w / 2 - cx) < (o.w / 2 + R) && o.y - bb.y < below + R && o.y - bb.y + o.h > below - R)
    /* from a touch area the stub starts at the control itself */
    return clash
      ? { cx, cy: b.y - LOOSE_GAP / 2 - R, edge: t ? t.y : b.y, up: true }
      : { cx, cy: below, edge: t ? t.y + t.h : b.y + b.h, up: false }
  }
  const jumpEdges = sub.edges.flatMap((e, i) => {
    const a = byId.get(e.from)
    const b = byId.get(e.to)
    return a && b && edgeKind(e) === 'back' && col(b) < col(a) ? [{ i, e, a, b }] : []
  })
  /* Several jumps back to ONE node (Close and Back both return to Control) landed on one spot,
     one connector over the other: spread them along the node, in edge order. */
  const into = new Map<string, number>()
  for (const j of jumpEdges) into.set(j.b.id, (into.get(j.b.id) ?? 0) + 1)
  const seenInto = new Map<string, number>()
  const jumps = jumpEdges.map((j, n) => {
    const m = into.get(j.b.id)!
    const k = seenInto.get(j.b.id) ?? 0
    seenInto.set(j.b.id, k + 1)
    const B = rel(j.b)
    const at = m > 1 ? { x: B.x + B.w * (0.25 + (0.5 * k) / (m - 1)), y: B.y, w: 0, h: B.h } : null
    return { i: j.i, e: j.e, from: spot(j.a, touchBox(j.e, j.a)), to: spot(j.b, at), letter: String.fromCharCode(65 + n) }
  })
  const stub = (sp: ReturnType<typeof spot>, out: boolean) => {
    const near = sp.up ? sp.cy + R : sp.cy - R
    return out ? [[sp.cx, sp.edge], [sp.cx, near]] : [[sp.cx, near], [sp.cx, sp.edge]]
  }
  /* ── routing: no two connectors share a segment ("เส้นไม่ควรทับกัน", Korn 2026-10-05) ──
     · a connector leaves from its Touch area when it has one
     · connectors meeting the same side of a node are spread along it (25%–75%), ordered by
       where their other end is, instead of all landing on its middle
     · every connector crossing a column gap turns in its OWN lane of that gap — they all used
       the gap's midpoint, so a red "No" and a purple "Remove" ran on one line */
  const paths = new Map<number, number[][]>()
  /* A connector between two screens of one column leaves the lower one through its caption;
     its label sits 3/4 of the way, near where it lands, so it never covers that caption. */
  const labelAt = new Map<number, number>()
  const labelScale = clamp(11 / (24 * k), guide, 3 * guide)
  /* a connector label's pill height on the board: 24/36 text + 8.5 padding top and bottom */
  const pill = (36 + 17) * labelScale
  /* labels that START at their point and read toward the target (a fan-out's) */
  const labelStart = new Set<number>()
  {
    /* COLUMNS, not node x: a column holding a 375 screen and a 197 decision used to give each
       its own "gap", and their lanes collided (FCD Open Account, 64 nodes, 2026-10-05).
       Gap g lies between column g-1 and column g. */
    type Mode = 'h' | 'v' | 'c' | 's'
    type Leg = { i: number; A: Box; B: Box; t: Box | null; from: string; to: string; ca: number; cb: number; mode: Mode; sx: number; sy: number; ex: number; ey: number; cyr: number }
    const at = (lo: number, len: number, n: number, k: number) => lo + len * (n === 1 ? 0.5 : 0.25 + (0.5 * k) / (n - 1))
    const cy = (b: Box) => b.y + b.h / 2
    const cx = (b: Box) => b.x + b.w / 2
    /* how close to a side's corner, or to another connector's port, a straight run may land */
    const inset = 24 * guide
    const colOf = (n: Placed) => n.col ?? 0
    const colL = new Map<number, number>()
    const colR = new Map<number, number>()
    for (const n of placed) {
      const b = rel(n)
      colL.set(colOf(n), Math.min(colL.get(colOf(n)) ?? Infinity, b.x))
      colR.set(colOf(n), Math.max(colR.get(colOf(n)) ?? -Infinity, b.x + b.w))
    }
    const gapL = (g: number) => colR.get(g - 1) ?? colL.get(g)! - RANK_GAP
    const gapR = (g: number) => colL.get(g) ?? colR.get(g - 1)! + RANK_GAP
    const boxesIn = (c: number) => placed.filter((n) => colOf(n) === c).map(rel)
    const blocked = (y: number, c0: number, c1: number) => {
      for (let c = c0; c <= c1; c++) if (boxesIn(c).some((b) => y > b.y - inset && y < b.y + b.h + inset)) return true
      return false
    }
    const legs: Leg[] = []
    sub.edges.forEach((e, i) => {
      if (jumps.some((j) => j.i === i)) return
      const a = byId.get(e.from)
      const b = byId.get(e.to)
      if (!a || !b) return
      const A = rel(a)
      const B = rel(b)
      const ca = colOf(a)
      const cb = colOf(b)
      const t = touchBox(e, a)
      const lo = Math.min(A.y + A.h, B.y + B.h)
      const hi = Math.max(A.y, B.y)
      const between = placed.some((n) => n.id !== a.id && n.id !== b.id && colOf(n) === ca && rel(n).y + rel(n).h > lo && rel(n).y < hi)
      /* h — into the next column, or further when nothing stands in the way · v — straight
         up/down to a neighbour in the same column · s — same column with a node between: round
         through the column's right gap · c — backward, or across columns that are in the way:
         out into its own lane, along the CORRIDOR under the main row, back in its own lane */
      const mode: Mode =
        cb === ca ? (between ? 's' : 'v')
        : cb === ca + 1 || (cb > ca && !blocked(cy(t ?? A), ca + 1, cb - 1) && !blocked(cy(B), ca + 1, cb - 1)) ? 'h'
        : 'c'
      legs.push({ i, A, B, t, from: e.from, to: e.to, ca, cb, mode, sx: 0, sy: 0, ex: 0, ey: 0, cyr: 0 })
    })
    const group = <K,>(list: Leg[], key: (l: Leg) => K) => {
      const m = new Map<K, Leg[]>()
      for (const l of list) m.set(key(l), [...(m.get(key(l)) ?? []), l])
      return [...m.values()]
    }
    const side = legs.filter((l) => l.mode !== 'v')
    for (const l of side) {
      if (l.t) [l.sx, l.sy] = [l.t.x + l.t.w, cy(l.t)]
    }
    /* Touch areas side by side in one row (a shortcut grid) all left at the row's middle and
       ran on one line: spread them over the row's shared height, left to right. Found on NA
       More Services (Scan | Transfer, nads 0.75.0, 2026-10-05). */
    for (const out of group(side.filter((l) => l.t), (l) => l.from)) {
      const rows: Leg[][] = []
      for (const l of [...out].sort((p, q) => p.t!.y - q.t!.y)) {
        const row = rows.find((r) => r.some((o) => o.t!.y < l.t!.y + l.t!.h && l.t!.y < o.t!.y + o.t!.h))
        if (row) row.push(l)
        else rows.push([l])
      }
      for (const row of rows) {
        if (row.length < 2) continue
        const lo = Math.max(...row.map((l) => l.t!.y))
        const hi = Math.min(...row.map((l) => l.t!.y + l.t!.h))
        row.sort((p, q) => p.t!.x - q.t!.x).forEach((l, k) => (l.sy = at(lo, hi - lo, row.length, k)))
      }
    }
    for (const out of group(side.filter((l) => !l.t), (l) => l.from)) {
      out.sort((p, q) => cy(p.B) - cy(q.B))
      out.forEach((l, k) => ([l.sx, l.sy] = [l.A.x + l.A.w, at(l.A.y, l.A.h, out.length, k)]))
    }
    /* the corridor: the empty band between the main row and the rows stacked under it — every
       c leg runs along it at its OWN height */
    const cs = legs.filter((l) => l.mode === 'c')
    if (cs.length) {
      const ys = placed.map(rel).sort((p, q) => p.y - q.y)
      let bottom = ys[0].y + ys[0].h
      let next = bottom + ROW_GAP
      for (const b of ys) {
        if (b.y > bottom + ROW_GAP / 2) {
          next = b.y
          break
        }
        bottom = Math.max(bottom, b.y + b.h)
      }
      const lo = bottom + (next - bottom) * 0.15
      const hi = bottom + (next - bottom) * 0.6
      cs.sort((p, q) => Math.min(p.ca, p.cb) - Math.min(q.ca, q.cb) || p.cb - q.cb).forEach((l, k) => (l.cyr = lo + ((hi - lo) * (k + 1)) / (cs.length + 1)))
    }
    for (const into of group(legs.filter((l) => l.mode === 'h' || l.mode === 'c'), (l) => l.to)) {
      into.sort((p, q) => (p.mode === 'c' ? p.cyr : p.sy) - (q.mode === 'c' ? q.cyr : q.sy))
      into.forEach((l, k) => ([l.ex, l.ey] = [l.B.x, at(l.B.y, l.B.h, into.length, k)]))
      /* fewest bends: a connector whose start height already falls on the target's side lands
         there, straight — unless another connector lands too close to it */
      for (const l of into) {
        if (l.mode !== 'h' || l.sy <= l.B.y + inset || l.sy >= l.B.y + l.B.h - inset) continue
        if (into.some((o) => o !== l && Math.abs(o.ey - l.sy) < inset)) continue
        l.ey = l.sy
      }
    }
    for (const into of group(legs.filter((l) => l.mode === 's'), (l) => l.to)) {
      into.sort((p, q) => p.sy - q.sy)
      into.forEach((l, k) => ([l.ex, l.ey] = [l.B.x + l.B.w, at(l.B.y, l.B.h, into.length, k)]))
    }
    /* every gap gives each connector crossing it its own lane: an h leg, a c leg's way out
       (gap after its source) and way in (gap before its target), an s leg's turn */
    type Mem = { l: Leg; inY: number; outY: number; part: 'h' | 'exit' | 'entry' | 's'; lane: number }
    const gaps = new Map<number, Mem[]>()
    const add = (g: number, m: Omit<Mem, 'lane'>) => gaps.set(g, [...(gaps.get(g) ?? []), { ...m, lane: 0 }])
    for (const l of legs) {
      if (l.mode === 'h') add(l.cb, { l, inY: l.sy, outY: l.ey, part: 'h' })
      if (l.mode === 's') add(l.ca + 1, { l, inY: l.sy, outY: l.ey, part: 's' })
      if (l.mode === 'c') {
        add(l.ca + 1, { l, inY: l.sy, outY: l.cyr, part: 'exit' })
        add(l.cb, { l, inY: l.cyr, outY: l.ey, part: 'entry' })
      }
    }
    const lanes = new Map<string, number>()
    for (const [g, gap] of gaps) {
      const left = gapL(g)
      const right = gapR(g)
      /* an s leg turns back the way it came: nearest the column it serves */
      gap.sort((p, q) => Number(q.part === 's') - Number(p.part === 's') || p.inY - q.inY || p.outY - q.outY)
      /* A connector that LEAVES at height y and one that ARRIVES at the same y share that row:
         the leaving one's lane must be left of the arriving one's, or their horizontals overlap
         (found on a 375 board: "No" into one screen and "Remove" out of its neighbour). Swap
         until no such pair is out of order. */
      for (let pass = 0; pass < gap.length; pass++) {
        let swapped = false
        for (let a = 0; a < gap.length; a++)
          for (let b = a + 1; b < gap.length; b++)
            if (gap[a].part !== 's' && gap[b].part !== 's' && Math.abs(gap[b].inY - gap[a].outY) < 1 && Math.abs(gap[a].inY - gap[a].outY) >= 1) {
              ;[gap[a], gap[b]] = [gap[b], gap[a]]
              swapped = true
            }
        if (!swapped) break
      }
      gap.forEach((m, k) => lanes.set(`${m.l.i}:${m.part}`, left + ((right - left) * (k + 1)) / (gap.length + 1)))
      for (const m of gap) {
        const l = m.l
        if (m.part !== 'h') continue
        if (Math.abs(l.sy - l.ey) < 1) {
          paths.set(l.i, [[l.sx, l.sy], [l.ex, l.ey]])
          continue
        }
        const lane = lanes.get(`${l.i}:h`)!
        paths.set(l.i, [[l.sx, l.sy], [lane, l.sy], [lane, l.ey], [l.ex, l.ey]])
        /* A fan-out (3+ connectors from one node through one gap, a shortcut grid) put every
           label at its lane's middle, where the lanes bunch: each label sits on its own lane
           just before it turns into its target, reading from the lane toward it (centred, it
           reached back over the column it came from). */
        const run = Math.abs(l.ey - l.sy)
        const off = l.B.h / 2 + pill / 2 + 8 * guide
        if (gap.filter((o) => o.part === 'h' && o.l.from === l.from).length >= 3 && run > off + pill / 2) {
          const out = Math.abs(lane - l.sx)
          labelAt.set(l.i, (out + run - off) / (out + run + Math.abs(l.ex - lane)))
          labelStart.add(l.i)
        }
      }
    }
    for (const l of legs) {
      if (l.mode === 's') {
        const lane = lanes.get(`${l.i}:s`)!
        paths.set(l.i, [[l.sx, l.sy], [lane, l.sy], [lane, l.ey], [l.ex, l.ey]])
      }
      if (l.mode === 'c') {
        const out = lanes.get(`${l.i}:exit`)!
        const inn = lanes.get(`${l.i}:entry`)!
        paths.set(l.i, [[l.sx, l.sy], [out, l.sy], [out, l.cyr], [inn, l.cyr], [inn, l.ey], [l.ex, l.ey]])
        /* its label rides the corridor, where nothing else is */
        const p = paths.get(l.i)!
        const len = p.slice(1).reduce((n, q, j) => n + Math.hypot(q[0] - p[j][0], q[1] - p[j][1]), 0)
        const upTo = Math.abs(out - l.sx) + Math.abs(l.cyr - l.sy)
        labelAt.set(l.i, (upTo + Math.abs(inn - out) / 2) / len)
      }
    }
    /* same-column legs (one above the other, nothing between): out of the facing side */
    const v = legs.filter((l) => l.mode === 'v')
    for (const into of group(v, (l) => l.to)) {
      into.sort((p, q) => (p.t ? cx(p.t) : cx(p.A)) - (q.t ? cx(q.t) : cx(q.A)))
      into.forEach((l, k) => {
        const down = cy(l.B) > cy(l.A)
        const src = l.t ?? l.A
        const sx = cx(src)
        const sy = down ? src.y + src.h : src.y
        /* fewest bends: straight down (or up) when the target is under the source */
        const ex = into.length === 1 && sx > l.B.x + inset && sx < l.B.x + l.B.w - inset ? sx : at(l.B.x, l.B.w, into.length, k)
        const ey = down ? l.B.y : l.B.y + l.B.h
        const my = down ? (l.A.y + l.A.h + l.B.y) / 2 : (l.B.y + l.B.h + l.A.y) / 2
        paths.set(l.i, Math.abs(sx - ex) < 1 ? [[sx, sy], [ex, ey]] : [[sx, sy], [sx, my], [ex, my], [ex, ey]])
        labelAt.set(l.i, 0.75)
      })
    }
  }
  const mainIds = useMemo(() => mainOf(sub.nodes, sub.edges), [sub])
  const [flash, setFlash] = useState<string | null>(null)
  useEffect(() => {
    if (!flash) return
    const t = setTimeout(() => setFlash(null), 1400)
    return () => clearTimeout(t)
  }, [flash])
  /* Connector labels are part of the drawing, as in the guideline: drawn at its 24 px scaled
     with the symbols, shown once that reads (>= 9 px on screen) and hidden at overview zoom,
     where the line colours carry the meaning. Counter-scaling them, like the screen captions,
     made their filled pills cover the whole flow when zoomed out. */
  /* Native 24 px per 1920 of screen, as the CNH board draws them; grown when zoomed out so
     they still read (11 px on screen), but never past 3x native — uncapped, their pills covered
     the flow. Hidden below that. */
  const showEdgeLabels = 24 * labelScale * k >= 9
  /* Where each connector's label sits. A label that would cover one already placed SLIDES
     ALONG ITS OWN LINE (0.35, 0.65, 0.25 …) until it is clear; a fan-out's labels keep their
     place by the target. A label with no clear spot on its line is not drawn at this zoom — the line's
     colour still says what it is, and zooming in shrinks the labels until it fits. Widths are
     estimated: BBL Sans Bold 24 measured up to 17 px a character (short capitals, 2026-10-05). */
  const labelSpots = new Map<number, number[]>()
  {
    const taken: Box[] = []
    const rectOf = (i: number, label: string, [x, y]: number[]): Box => {
      const w = (label.length * 17 + 25.5) * labelScale
      return labelStart.has(i) ? { x: x + stroke * 2, y: y - pill / 2, w, h: pill } : { x: x - w / 2, y: y - pill / 2, w, h: pill }
    }
    const hits = (r: Box) => taken.some((t) => r.x < t.x + t.w && t.x < r.x + r.w && r.y < t.y + t.h && t.y < r.y + r.h)
    /* a screen's caption is taken first: a label slides off it as it slides off another label */
    if (showLabels)
      for (const n of placed)
        if (n.kind === 'screen') {
          const b = rel(n)
          taken.push({ x: b.x, y: b.y - CAPTION_H * labelK, w: b.w, h: CAPTION_H * labelK })
        }
    const order = sub.edges.map((e, i) => i).sort((p, q) => Number(labelStart.has(q)) - Number(labelStart.has(p)))
    for (const i of order) {
      const e = sub.edges[i]
      const a = byId.get(e.from)
      const b = byId.get(e.to)
      if (!a || !b || !e.label) continue
      const j = jumps.find((x) => x.i === i)
      /* a jump's label sits 3/4 down its stub, by the connector it names: a stub from a touch
         area runs the screen's height, and its middle lay level with the next column's labels */
      const line = j ? stub(j.from, true) : (paths.get(i) ?? elbow(rel(a), rel(b)))
      const base = j ? 0.75 : (labelAt.get(i) ?? 0.5)
      const tries = labelStart.has(i) ? [base] : [base, 0.35, 0.65, 0.25, 0.75, 0.15, 0.85, 0.1, 0.9, 0.05, 0.95]
      let spot: number[] | null = null
      for (const f of tries) {
        const at = halfway(line, f)
        if (!hits(rectOf(i, e.label, at))) {
          spot = at
          break
        }
      }
      if (!spot) continue
      labelSpots.set(i, spot)
      taken.push(rectOf(i, e.label, spot))
    }
  }
  const counts = {
    screens: placed.filter((n) => n.kind === 'screen').length,
    decisions: placed.filter((n) => n.kind === 'decision').length,
  }
  const src = graph.source
  const provenance =
    (src.kind ?? 'figma') === 'code' ? `unfolded from code · ${src.path} · ${src.extractedAt}` : `Figma ${src.file} ${src.node} · ${src.extractedAt}`

  return (
    <div className={cn('webds-tfv', className)}>
      <div className="webds-tfv-toolbar">
        <p className="webds-tfv-title">Task flow</p>
        <div className="webds-tfv-chips">
          {sections.length > 1 && (
            <>
              <Chip state={section === WHOLE ? 'selected' : 'default'} appearance="highlight" onClick={() => setSection(WHOLE)}>
                Whole flow
              </Chip>
              {sections.map((s) => (
                <Chip key={s.name} state={section === s.name ? 'selected' : 'default'} appearance="highlight" onClick={() => setSection(s.name)}>
                  {`${short(s.name)} · ${s.count}`}
                </Chip>
              ))}
            </>
          )}
        </div>
        <div className="webds-tfv-group">
          <Chip state={!wf ? 'selected' : 'default'} appearance="highlight" onClick={() => setWf(false)}>
            Hi-fi
          </Chip>
          <Chip state={wf ? 'selected' : 'default'} appearance="highlight" onClick={() => setWf(true)}>
            Wireframe
          </Chip>
        </div>
        <div className="webds-tfv-group">
          {/* ×2 a click (×1.4 needed a dozen clicks from the whole flow to a readable screen);
              100% shows a screen at its real size around the centre of the view. */}
          <OutlineButton onClick={() => zoomTo((k) => k / 2)} aria-label="Zoom out">−</OutlineButton>
          <span className="webds-tfv-zoom" aria-live="polite">{`${Math.round(k * 100)}%`}</span>
          <OutlineButton onClick={() => zoomTo((k) => k * 2)} aria-label="Zoom in">+</OutlineButton>
          <OutlineButton onClick={() => zoomTo(() => 1)}>100%</OutlineButton>
          <OutlineButton onClick={fit}>Fit</OutlineButton>
        </div>
      </div>

      <div
        ref={port}
        className="webds-tfv-canvas"
        onPointerDown={onPointerDown}
        onPointerMove={onPointerMove}
        onPointerUp={onPointerUp}
        onPointerCancel={onPointerUp}
      >
        <div className="webds-tfv-board" style={{ transform: `translate(${view.tx}px, ${view.ty}px) scale(${k})`, width: bb.w, height: bb.h }}>
          {placed.map((n) => {
            const b = rel(n)
            const current = !!n.route && n.route === currentRoute
            const ring = current ? { boxShadow: `0 0 0 ${Math.max(8, 3 / k)}px var(--color-border-highlight-default)` } : undefined
            const clickable = !!n.route && !!onOpen
            const common = {
              role: clickable ? 'button' : undefined,
              tabIndex: clickable ? 0 : undefined,
              title: n.route ? `${n.route} · ${n.label}` : n.label,
              onClick: clickable ? () => open(n.route) : undefined,
              onKeyDown: clickable ? (e: KeyboardEvent) => e.key === 'Enter' && open(n.route) : undefined,
            }
            const at = { left: b.x, top: b.y, width: b.w }
            if (n.kind === 'screen') {
              const live = !!n.route && inView(n) && n.w * k >= SCREEN_MIN_PX
              return (
                <div key={n.id} {...common} className={cn('webds-tfv-node', clickable && 'webds-tfv-node--open')} style={{ ...at, height: b.h, ...ring }}>
                  {live ? (
                    <ScreenNode route={n.route!} w={n.w} h={n.h} renderScreen={renderScreen} wireframe={wf} />
                  ) : (
                    <div className="webds-tfv-placeholder" />
                  )}
                  {showLabels && (
                    <div className="webds-tfv-caption" style={{ transform: `scale(${labelK})`, width: n.w / labelK }}>
                      <p className="webds-tfv-caption-route">{n.route ?? 'no route'}</p>
                      <p className="webds-tfv-caption-label">{n.label}</p>
                    </div>
                  )}
                </div>
              )
            }
            if (n.kind === 'note') {
              return (
                <div key={n.id} title={n.label} className="webds-tfv-node webds-tfv-note" style={{ ...at, height: b.h }}>
                  <p className="webds-tfv-note-text" style={fitted(n)}>
                    {n.label}
                  </p>
                </div>
              )
            }
            /* 4.1 "Diamond" — in the guideline a purple box with a small white diamond over the
               question, not a diamond-shaped node. */
            if (n.kind === 'decision') {
              return (
                <div key={n.id} {...common} className="webds-tfv-node" style={{ ...at, height: b.h }}>
                  <div className="webds-tfv-fit webds-tfv-symbol webds-tfv-decision" style={fitted(n)}>
                    <span className="webds-tfv-decision-mark" aria-hidden />
                    <p className="webds-tfv-symbol-text">{n.label}</p>
                  </div>
                </div>
              )
            }
            /* 4.3 "Process" — purple on the main flow; grey off it, as the guideline's own
               examples draw alternative endpoints (its library ships the purple one only). */
            return (
              <div key={n.id} {...common} className={cn('webds-tfv-node', clickable && 'webds-tfv-node--open')} style={{ ...at, height: b.h, ...ring }}>
                <div className={cn('webds-tfv-fit webds-tfv-symbol webds-tfv-process', !mainIds.has(n.id) && 'webds-tfv-symbol--alt')} style={fitted(n)}>
                  <p className="webds-tfv-symbol-text">{n.label}</p>
                </div>
              </div>
            )
          })}

          <svg className="webds-tfv-edges" width={bb.w} height={bb.h}>
            {/* The guideline's caps: a filled diamond where the connector leaves (DIAMOND_FILLED)
                and an open arrow where it lands (ARROW_LINES). */}
            <defs>
              {EDGE_KINDS.map((key) => (
                <g key={key}>
                  <marker id={`webds-tfv-start-${key}`} viewBox="0 0 10 10" refX="5" refY="5" markerWidth="3" markerHeight="3" orient="auto">
                    <path d="M0 5 L5 0 L10 5 L5 10 z" className={`webds-tfv-ink--${key}`} />
                  </marker>
                  <marker id={`webds-tfv-end-${key}`} viewBox="0 0 10 10" refX="9" refY="5" markerWidth="3.5" markerHeight="3.5" orient="auto">
                    <path d="M1 1 L9 5 L1 9" className={`webds-tfv-ink--${key} webds-tfv-arrowhead`} />
                  </marker>
                </g>
              ))}
            </defs>
            {sub.edges.map((e, i) => {
              const a = byId.get(e.from)
              const b = byId.get(e.to)
              if (!a || !b) return null
              const kind = edgeKind(e)
              const dash = kind === 'inferred' ? `${stroke} ${stroke * 2.5}` : kind === 'solid' ? undefined : `${stroke * 2} ${stroke * 2}`
              const j = jumps.find((x) => x.i === i)
              const lines = j ? [stub(j.from, true), stub(j.to, false)] : [paths.get(i) ?? elbow(rel(a), rel(b))]
              return lines.map((pts, n) => (
                <polyline
                  key={`${i}-${n}`}
                  points={pts.map((p) => p.join(',')).join(' ')}
                  className={`webds-tfv-edge webds-tfv-ink--${kind}`}
                  strokeWidth={kind === 'inferred' ? stroke * 0.75 : stroke}
                  strokeDasharray={dash}
                  markerStart={n === 0 ? `url(#webds-tfv-start-${kind})` : undefined}
                  markerEnd={`url(#webds-tfv-end-${kind})`}
                />
              ))
            })}
            {sub.edges.map((e, i) => {
              const a = byId.get(e.from)
              const t = a ? touchBox(e, a) : null
              return t ? (
                <rect
                  key={`t${i}`}
                  x={t.x}
                  y={t.y}
                  width={t.w}
                  height={t.h}
                  rx={4 * guide}
                  className="webds-tfv-touch"
                  strokeWidth={Math.max(2 * guide, 1.5 / k)}
                  strokeDasharray={`${Math.max(8 * guide, 3 / k)} ${Math.max(8 * guide, 3 / k)}`}
                />
              ) : null
            })}
          </svg>

          {jumps.flatMap((j) =>
            [j.from, j.to].map((sp, n) => {
              /* A connector is a jump: clicking one brings its partner to the centre of the view
                 and rings it for a moment, so the eye lands on the other end. */
              const other = n === 0 ? j.to : j.from
              const go = () => {
                if (dragged.current) return
                setView((v) => ({ ...v, tx: size.w / 2 - other.cx * v.k, ty: size.h / 2 - other.cy * v.k }))
                setFlash(`${j.i}-${1 - n}`)
              }
              return (
              <div
                key={`c${j.i}-${n}`}
                role="button"
                tabIndex={0}
                className={cn('webds-tfv-node webds-tfv-node--open webds-tfv-jump', flash === `${j.i}-${n}` && 'webds-tfv-jump--flash')}
                title={`${j.letter}: ${j.e.label ?? 'jump'} — go to the other ${j.letter}`}
                onClick={go}
                onKeyDown={(e) => e.key === 'Enter' && go()}
                style={{ left: sp.cx - R, top: sp.cy - R, width: R * 2, height: R * 2 }}
              >
                <div className="webds-tfv-fit webds-tfv-connector" style={{ width: GUIDE.connector, height: GUIDE.connector, transform: `scale(${(R * 2) / GUIDE.connector})` }}>
                  <p className="webds-tfv-connector-letter">{j.letter}</p>
                </div>
              </div>
              )
            }),
          )}

          {showEdgeLabels &&
            sub.edges.map((e, i) => {
              const a = byId.get(e.from)
              const b = byId.get(e.to)
              if (!a || !b || !e.label) return null
              const at = labelSpots.get(i)
              if (!at) return null
              const [x, y] = at
              return (
                <p
                  key={`l${i}`}
                  className={`webds-tfv-edge-label webds-tfv-edge-label--${edgeKind(e)}`}
                  style={
                    labelStart.has(i)
                      ? { left: x, top: y, transformOrigin: 'left center', transform: `translate(${stroke * 2}px, -50%) scale(${labelScale})` }
                      : { left: x, top: y, transform: `translate(-50%, -50%) scale(${labelScale})` }
                  }
                >
                  {e.label}
                </p>
              )
            })}
          {showLabels &&
            [...sub.exits.entries()].map(([from, targets]) => {
              const a = byId.get(from)
              if (!a) return null
              const b = rel(a)
              return (
                <div key={`x${from}`} className="webds-tfv-exits" style={{ left: b.x + b.w, top: b.y, transform: `scale(${labelK})` }}>
                  {targets.map((t) => (
                    <button key={t.id} type="button" className="webds-tfv-exit" onPointerDown={(e) => e.stopPropagation()} onClick={() => goTo(t)}>
                      {`to ${short(t.route ?? t.label, 28)} · ${short(sectionOf(t), 24)}`}
                    </button>
                  ))}
                </div>
              )
            })}
        </div>

        <div className="webds-tfv-legend">
          {EDGE_KINDS.map((key) => (
            <span key={key} className="webds-tfv-legend-item">
              <svg width="28" height="6" className="webds-tfv-legend-swatch">
                <line
                  x1="0"
                  y1="3"
                  x2="28"
                  y2="3"
                  className={`webds-tfv-ink--${key}`}
                  strokeWidth={key === 'inferred' ? 1.5 : 2}
                  strokeDasharray={key === 'solid' ? undefined : key === 'inferred' ? '2 4' : '5 4'}
                />
              </svg>
              {EDGE_LABEL[key]}
            </span>
          ))}
          <span className="webds-tfv-legend-meta">Scroll or drag to move · pinch or ⌘/Ctrl + scroll to zoom</span>
          <span className="webds-tfv-legend-meta">{`${counts.screens} screens · ${counts.decisions} decisions · ${sub.edges.length} connectors · ${provenance}`}</span>
        </div>
      </div>
    </div>
  )
}

/* ── overlay host ─────────────────────────────────────────────────────────── */

export type TaskFlowOverlayProps = {
  graph: FlowGraph
  renderScreen: TaskFlowRenderScreen
  /** The route the prototype is showing — highlighted. */
  currentRoute?: string
  /** A screen (or a routed terminal) was clicked: go there. The overlay closes itself. */
  onNavigate?: (route: string) => void
  /** Prototype name, shown in the overlay's header line. */
  title?: string
}

/* The "Task flow" button and the full-window view behind it. The trigger floats at the
   window's bottom-right; `?flow=1` opens the overlay on load and `&wf=1` starts it in
   wireframe; Esc or Close shuts it. It is dev chrome, not product UI — mount it in a
   prototype's RUNNER, never in the source handed to a dev team.
   ASSIGNED: the trigger's corner and the header copy. */
export function TaskFlowOverlay({ graph, renderScreen, currentRoute, onNavigate, title }: TaskFlowOverlayProps) {
  const [params] = useState(() => new URLSearchParams(typeof location === 'undefined' ? '' : location.search))
  const [open, setOpen] = useState(() => params.get('flow') === '1')
  useEffect(() => {
    if (!open) return
    const onKey = (e: globalThis.KeyboardEvent) => e.key === 'Escape' && setOpen(false)
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [open])

  if (!open)
    return (
      <div className="webds-tfv-trigger">
        <OutlineButton onClick={() => setOpen(true)}>Task flow</OutlineButton>
      </div>
    )
  return (
    <div role="dialog" aria-modal="true" aria-label="Task flow" className="webds-tfv-overlay">
      <div className="webds-tfv-overlay-head">
        <p className="webds-tfv-legend-meta">
          {`${title ? `${title} — ` : ''}task flow${currentRoute ? ` around ${currentRoute}` : ''}. Click a screen to open it · Esc closes`}
        </p>
        <OutlineButton onClick={() => setOpen(false)}>Close</OutlineButton>
      </div>
      <div className="webds-tfv-overlay-body">
        <TaskFlowView
          graph={graph}
          renderScreen={renderScreen}
          currentRoute={currentRoute}
          wireframe={params.get('wf') === '1'}
          onOpen={
            onNavigate &&
            ((route) => {
              setOpen(false)
              onNavigate(route)
            })
          }
        />
      </div>
    </div>
  )
}
