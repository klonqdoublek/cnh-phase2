function sectionsOf(graph: FlowGraph) {
  const at = new Map<string, Box[]>()
  for (const n of graph.nodes) {
    const s = sectionOf(n)
    if (!at.has(s)) at.set(s, [])
    if (n.x != null && n.y != null) at.get(s)!.push({ x: n.x, y: n.y, w: n.w ?? 0, h: n.h ?? 0 })
  }
  return [...at.entries()]
    .map(([name, boxes]) => ({ name, box: bboxOf(boxes), count: graph.nodes.filter((n) => n.kind !== 'note' && sectionOf(n) === name).length }))
    .sort((a, b) => Math.floor(a.box.y / SECTION_ROW) - Math.floor(b.box.y / SECTION_ROW) || a.box.x - b.box.x)
}

